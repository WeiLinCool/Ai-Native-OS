#!/usr/bin/env python3
"""Record bilingual pairing sidecars (README.i18n.yaml) for every README.

The pairing gate (scripts/verify-translation-pairing.ts) enforces a three-file
triplet per in-scope README:

    README.md          English source
    README.zh.md       Chinese counterpart
    README.i18n.yaml   consistency record - git blob hash of each file

This script writes the third file. Run it after translating a README, or after
editing a source README, then run the gate to confirm the pair is consistent:

    python scripts/i18n-record.py                   # every in-scope README
    python scripts/i18n-record.py --only handbook   # just one subtree
    node --experimental-strip-types scripts/verify-translation-pairing.ts --config docs-constraint.yaml

The in-scope source list comes from the gate itself (--list), so the two never
disagree about which files are covered.

Exit codes: 0 when every source has a recorded sidecar, 1 when a counterpart is
still missing (nothing is recorded for that file).
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GATE = os.path.join("scripts", "verify-translation-pairing.ts")
LIST_RE = re.compile(r"^\s+(?:ok|FAIL)\s+(\S+)$")


def gate_sources(config: str) -> list[str]:
    """Ask the gate which READMEs are in scope (single source of truth)."""
    result = subprocess.run(
        ["node", "--experimental-strip-types", GATE, "--config", config, "--list"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.exit("could not list pairs: " + result.stderr.strip())
    return [m.group(1) for m in (LIST_RE.match(line) for line in result.stdout.splitlines()) if m]


def suffix_map(config: str) -> dict[str, str]:
    """Read i18n.suffix_map from the constrained YAML config."""
    mapping: dict[str, str] = {}
    in_block = False
    with open(os.path.join(ROOT, config), encoding="utf-8") as fh:
        for line in fh:
            stripped = line.split("#", 1)[0].rstrip()
            if not stripped.strip():
                continue
            if re.match(r"^\s*suffix_map:\s*$", stripped):
                in_block = True
                continue
            if in_block:
                m = re.match(r"^\s+([\w-]+):\s*\"?([^\"\s]+)\"?\s*$", stripped)
                if m:
                    mapping[m.group(1)] = m.group(2)
                elif not stripped.startswith(" "):
                    break
    return mapping


def gate_hash(path: str) -> str:
    """Reproduce the gate's blob hash exactly.

    The gate measures the header length the way JavaScript counts it (UTF-16
    code units) while hashing the UTF-8 body, so a sidecar written with git's
    own blob hash would mismatch on any file containing non-ASCII characters.
    """
    with open(path, "rb") as fh:
        data = fh.read()
    utf16_units = len(data.decode("utf-8").encode("utf-16-le")) // 2
    return hashlib.sha1(b"blob %d\0" % utf16_units + data).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description="Record bilingual pairing sidecars.")
    parser.add_argument("--config", default="docs-constraint.yaml")
    parser.add_argument("--only", action="append", default=[],
                        help="limit to sources under this path (repeatable)")
    args = parser.parse_args()

    suffixes = suffix_map(args.config)
    if not suffixes:
        sys.exit("no i18n.suffix_map entries found in " + args.config)

    sources = gate_sources(args.config)
    if args.only:
        wanted = [o.rstrip("/") for o in args.only]
        sources = [s for s in sources if any(s == w or s.startswith(w + "/") for w in wanted)]

    written = 0
    missing: list[str] = []
    for source in sources:
        stem, _ = os.path.splitext(source)
        records = [(os.path.basename(source), gate_hash(os.path.join(ROOT, source)))]
        absent = False
        for _lang, suffix in sorted(suffixes.items()):
            counterpart = stem + suffix
            if not os.path.exists(os.path.join(ROOT, counterpart)):
                missing.append(counterpart)
                absent = True
                continue
            records.append((os.path.basename(counterpart), gate_hash(os.path.join(ROOT, counterpart))))
        if absent:
            continue

        body = ["# Bilingual pairing record - generated by scripts/i18n-record.py"]
        body += [name + ": " + digest for name, digest in records]
        with open(os.path.join(ROOT, stem + ".i18n.yaml"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(body) + "\n")
        written += 1

    print("Recorded " + str(written) + " sidecar(s) for " + str(len(sources)) + " in-scope source file(s).")
    if missing:
        print(str(len(missing)) + " counterpart(s) still missing:")
        for path in missing[:20]:
            print("  " + path)
        if len(missing) > 20:
            print("  ... and " + str(len(missing) - 20) + " more")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
